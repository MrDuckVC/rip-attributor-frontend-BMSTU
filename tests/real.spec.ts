import { expect, test } from '@playwright/test'

test('real Go/PostgreSQL/Redis/S3: upload, publish, like, signed proxy, F5, delete, blacklist', async ({ page, request }) => {
  test.skip(process.env.LAB6_REAL_API !== '1', 'Requires isolated real backend; see docs/lab6/verification.md')
  const login = `lab6_${Date.now()}`
  const credentials = { login, password: 'lab6-verification-only' }
  const register = await request.post('/api/users', { data: credentials })
  expect(register.status()).toBe(201)
  await page.goto('/login')
  await page.getByLabel('Логин', { exact: true }).fill(login)
  await page.getByLabel('Пароль', { exact: true }).fill(credentials.password)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Выход' })).toBeVisible()
  await page.getByRole('link', { name: 'Добавить', exact: true }).click()
  await page.getByLabel('Изображение', { exact: true }).setInputFiles('public/media/puskin.png')
  await page.getByLabel('Вертикальное видео', { exact: true }).setInputFiles('public/media/puskin.mp4')
  await page.getByLabel('Название корпуса', { exact: true }).fill(`Пушкин, ${login}`)
  await page.getByRole('button', { name: 'Создать черновик' }).click()
  await expect(page.getByRole('button', { name: 'Опубликовать' })).toBeVisible()
  const image = page.getByRole('img', { name: `Пушкин, ${login}` })
  await expect(image).toHaveAttribute('src', /^\/s3\/corpora\/.+X-Amz-Signature=/)
  await expect.poll(() => image.evaluate(node => (node as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  const signedURL = await image.getAttribute('src')
  const media = await request.get(signedURL!)
  expect(media.status()).toBe(200)
  const tampered = signedURL!.replace(/X-Amz-Signature=./, 'X-Amz-Signature=z')
  expect((await request.get(tampered)).status()).toBe(403)
  await page.getByLabel('Описание', { exact: true }).fill('Реальная проверка корпуса')
  await page.getByLabel('Количество слов', { exact: true }).fill('55000')
  await page.getByLabel('Процент предлогов', { exact: true }).fill('8.5')
  await page.getByRole('button', { name: 'Опубликовать' }).click()
  await expect(page).toHaveURL(/\/corpora\/\d+$/)
  const id = Number(new URL(page.url()).pathname.split('/').at(-1))
  await expect.poll(() => page.getByLabel('Видео корпуса').evaluate(node => (node as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2)
  await page.getByRole('button', { name: 'Поставить лайк' }).click()
  await expect(page.getByRole('button', { name: 'Снять лайк' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Лайк — требуется вход' })).toBeDisabled()
  const token = await page.evaluate(() => localStorage.getItem('attributor.access_token'))
  expect(token).toBeTruthy()
  const catalog = await request.get('/api/corpora?query=50000&page=1', { headers: { Authorization: `Bearer ${token}` } })
  expect((await catalog.json()).items.find((item: { id: number }) => item.id === id).is_owner).toBe(1)
  await page.getByRole('link', { name: 'Вход', exact: true }).click()
  await page.getByLabel('Логин', { exact: true }).fill(login)
  await page.getByLabel('Пароль', { exact: true }).fill(credentials.password)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await page.getByRole('button', { name: `Удалить корпус: Пушкин, ${login}` }).click()
  await expect(page.getByText('Корпусы не найдены')).toBeVisible()
  const logoutToken = await page.evaluate(() => localStorage.getItem('attributor.access_token'))
  await page.getByRole('button', { name: 'Выход' }).click()
  await expect(page.getByRole('link', { name: 'Вход', exact: true })).toBeVisible()
  expect((await request.get('/api/corpora/draft', { headers: { Authorization: `Bearer ${logoutToken}` } })).status()).toBe(401)
})
